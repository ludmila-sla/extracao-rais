def secao(cod):
    if pd.isna(cod):
        return None
    d = "".join(ch for ch in str(cod) if ch.isdigit())
    if not d:
        return None
    div = int(d.zfill(7)[:2])
    for ini, fim, letra, desc in SECOES:
        if ini <= div <= fim:
            return desc
    return None

