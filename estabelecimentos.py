# ============ CÉLULA 5: geocodificação por CEP (com cache e retomada) ============
CACHE = os.path.join(PASTA, "cache_cep_latlon.json")
os.makedirs(PASTA, exist_ok=True)
cache = json.load(open(CACHE)) if os.path.exists(CACHE) else {}

def geocodar(cep):
    if cep in cache:
        return cep, cache[cep]
    res = [None, None]
    for tentativa in range(3):
        try:
            r = requests.get(f"https://cep.awesomeapi.com.br/json/{cep}", timeout=15)
            if r.status_code == 200:
                j = r.json()
                if j.get("lat") and j.get("lng"):
                    res = [float(j["lat"]), float(j["lng"])]
                    break
            elif r.status_code == 429:
                time.sleep(2 * (tentativa + 1)); continue
            break
        except Exception:
            time.sleep(1)
    if res[0] is None:
        try:
            r = requests.get(f"https://brasilapi.com.br/api/cep/v2/{cep}", timeout=15)
            if r.status_code == 200:
                c = r.json().get("location", {}).get("coordinates", {})
                if c.get("latitude"):
                    res = [float(c["latitude"]), float(c["longitude"])]
        except Exception:
            pass
    return cep, res

ceps = [c for c in df["cep"].dropna().unique() if c not in ("00000000",) and len(c) == 8]
pendentes = [c for c in ceps if c not in cache]
print(f"{len(ceps)} CEPs únicos; {len(pendentes)} a geocodificar.")

with ThreadPoolExecutor(max_workers=5) as ex:
    for i, (cep, res) in enumerate(tqdm(ex.map(geocodar, pendentes), total=len(pendentes))):
        cache[cep] = res
        if i % 200 == 0:
            json.dump(cache, open(CACHE, "w"))
json.dump(cache, open(CACHE, "w"))

